// ============================================================
// 示例 1: 点亮 ESP32-S3 板载 RGB 灯 (实测跑通)
// 目标板: ESP32-S3-N16R8 (板载 WS2812, 数据脚 GPIO48, 供电脚 GPIO47)
//
// 用法 (DUANYAN-IDE):
//   1. 本文件可直接在编辑器中打开、修改
//   2. FlashPanel 选择目标 "esp32s3-bare" → 编译出 .bin
//   3. DUANYAN 烧录器把 .bin 烧进开发板
//
// 效果: RGB 灯常亮白色 (红绿蓝三色全开)
// ============================================================

import { RGB, Timer } from "hardy:hw";

// 常亮白色: 每 500ms 刷新一次 WS2812 数据
while (true) {
    RGB.setColor(255, 255, 255);
    Timer.delay(500);
}
