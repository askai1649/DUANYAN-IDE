// ============================================================
// 示例 2: ESP32-S3 板载 RGB 灯彩虹渐变 (实测跑通)
// 目标板: ESP32-S3-N16R8 (板载 WS2812, 数据脚 GPIO48, 供电脚 GPIO47)
//
// 用法 (DUANYAN-IDE):
//   1. 本文件可直接在编辑器中打开、修改
//   2. FlashPanel 选择目标 "esp32s3-bare" → 编译出 .bin
//   3. DUANYAN 烧录器把 .bin 烧进开发板
//
// 效果: RGB 灯沿 HSV 色轮平滑流转, 红→黄→绿→青→蓝→紫 循环
//       每帧 12ms 步进 1 度, 一轮彩虹约 3 秒, 丝滑无闪烁 (亮度 1/4 防眩眼)
// 可玩: 改 Timer.delay(12) 的数字调节流速, 数字越小转得越快
// ============================================================

import { RGB, Timer } from "hardy:hw";

let hue = 0;

while (true) {
    RGB.setHue(hue);
    hue = hue + 1;
    if (hue >= 256) {
        hue = 0;
    }
    Timer.delay(12);
}
